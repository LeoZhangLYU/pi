/** A bot's status words (the list row), translated. */
export type DiscordTranslator = Translator<"p2.discord", MessagesOf<typeof discordMessages>>;

export const statusText = (t: DiscordTranslator, status: BotStatus): string =>
	status.state === "connecting"
		? t("connecting")
		: status.state === "error"
			? t("notConnected")
			: t("serversCount", status.guilds.length);
